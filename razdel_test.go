func TestTokenize(t *testing.T) {
	for _, tt := range tokenizeTests {
		t.Run(tt.text, func(t *testing.T) {
			got := Tokenize(tt.text)
			if !reflect.DeepEqual(got, tt.expected) {
				t.Errorf("Tokenize(%q) = %v, want %v", tt.text, got, tt.expected)
			}
		})
	}
}

func TestSentenize(t *testing.T) {
	for _, tt := range sentenizeTests {
		t.Run(tt.text, func(t *testing.T) {
			got := Sentenize(tt.text)
			if !reflect.DeepEqual(got, tt.expected) {
				t.Errorf("Sentenize(%q) =\n%v\nwant\n%v", tt.text, got, tt.expected)
			}
		})
	}
}
